/** Messaggio dentro un altro (il motivo di "Import non eseguito: …"): stessa traduzione di tServer */
function inner(text) {
  if (text in strings) return strings[text]
  const found = patterns.find(([pattern]) => pattern.test(text))
  return found ? text.replace(found[0], found[1]) : text
}

